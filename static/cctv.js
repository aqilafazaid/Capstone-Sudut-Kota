/* ===================================================
   LOGIKA RENDER GRID CCTV & FILTER TIPE
=================================================== */
function renderCCTVGrid() {
    const container = document.getElementById('cctv-grid-container');
    const filterTipe = document.getElementById('filter-tipe');
    
    if(!container || !filterTipe) return; 

    const filterValue = filterTipe.value;
    container.innerHTML = ''; 
    let renderedCount = 0;

    cctvDatabase.forEach(cam => {
        if (filterValue !== 'semua' && cam.tipe !== filterValue) return;
        renderedCount++;

        let badgeHTML = '';
        let borderClass = '';
        
        if (cam.tipe === 'ai') {
            badgeHTML = `
                <div class="absolute top-3 left-3 bg-blue-600 text-white text-[9px] font-bold px-2.5 py-1 rounded-md uppercase tracking-widest z-20 flex items-center gap-2 shadow-md">
                    <i class="fa-solid fa-microchip animate-pulse text-yellow-300"></i> AI YOLOv8
                </div>`;
            borderClass = 'border-blue-500 shadow-[0_0_15px_rgba(37,99,235,0.3)]';
        } else {
            badgeHTML = `
                <div class="absolute top-3 left-3 bg-red-600 text-white text-[9px] font-bold px-2.5 py-1 rounded-md uppercase tracking-widest z-20 flex items-center gap-2 shadow-md">
                    <span class="w-1.5 h-1.5 bg-white rounded-full animate-pulse"></span> RAW NVR
                </div>`;
            borderClass = 'border-slate-200 dark:border-slate-800 shadow-lg';
        }

        let playerHTML = '';
        if (cam.url.includes('.php')) {
            playerHTML = `<iframe src="${cam.url}" class="w-full h-full object-cover border-0 pointer-events-none" allowfullscreen></iframe>`;
        } else {
            playerHTML = `<video id="video-${cam.id}" class="w-full h-full object-cover" muted autoplay playsinline></video>`;
        }

        const cardHTML = `
            <div class="bg-white dark:bg-[#0f172a] rounded-2xl overflow-hidden ${borderClass} hover:shadow-xl transition-shadow flex flex-col group relative">
                <div class="relative bg-black aspect-video flex items-center justify-center overflow-hidden">
                    ${badgeHTML}
                    ${playerHTML}
                </div>
                <div class="p-4 flex-grow flex flex-col justify-between border-t ${cam.tipe === 'ai' ? 'border-blue-500/50' : 'border-slate-200 dark:border-slate-800'}">
                    <h3 class="font-black text-slate-800 dark:text-white text-sm mb-3 uppercase tracking-wide truncate" title="${cam.nama}">${cam.nama}</h3>
                    <div class="flex items-center gap-2">
                        <span class="bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 border border-slate-200 dark:border-slate-700 text-[10px] font-bold px-2.5 py-1 rounded-md flex items-center gap-1.5">
                            <i class="fa-solid fa-signal text-green-500"></i> ${cam.status}
                        </span>
                        <span class="bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 border border-slate-200 dark:border-slate-700 text-[10px] font-bold px-2.5 py-1 rounded-md flex items-center gap-1.5">
                            <i class="fa-regular fa-eye ${cam.publik ? 'text-blue-500' : 'text-red-500'}"></i> ${cam.publik ? 'Publik' : 'Privat'}
                        </span>
                    </div>
                </div>
            </div>
        `;
        container.innerHTML += cardHTML;
    });

    const streamCountEl = document.getElementById('stream-count');
    if(streamCountEl) {
        streamCountEl.innerHTML = `<i class="fa-solid fa-video"></i> ${renderedCount} Stream Aktif`;
    }
    
    initHLSPlayers(filterValue);
}

/* ===================================================
   INISIALISASI PEMUTAR HLS NATIVE (.m3u8)
=================================================== */
function initHLSPlayers(filterValue) {
    cctvDatabase.forEach(cam => {
        if ((filterValue !== 'semua' && cam.tipe !== filterValue) || cam.url.includes('.php')) return;

        const video = document.getElementById(`video-${cam.id}`);
        if (!video) return;

        if (window.Hls && Hls.isSupported()) {
            const hls = new Hls({ debug: false, enableWorker: true });
            hls.loadSource(cam.url);
            hls.attachMedia(video);
            hls.on(Hls.Events.MANIFEST_PARSED, function() {
                video.play().catch(e => console.log("Autoplay ditahan browser"));
            });
        } else if (video.canPlayType('application/vnd.apple.mpegurl')) {
            video.src = cam.url;
            video.addEventListener('loadedmetadata', function() {
                video.play();
            });
        }
    });
}

/* ===================================================
   JAM & SAPAAN REALTIME DASHBOARD
=================================================== */
function updateAppHeader() {
    const now = new Date();
    const hours = now.getHours();
    
    let greeting = "Selamat Malam";
    let iconClass = "fa-moon";
    let iconColor = "text-blue-300";

    if (hours >= 4 && hours < 11) { greeting = "Selamat Pagi"; iconClass = "fa-cloud-sun"; iconColor = "text-yellow-400"; } 
    else if (hours >= 11 && hours < 15) { greeting = "Selamat Siang"; iconClass = "fa-sun"; iconColor = "text-yellow-300"; } 
    else if (hours >= 15 && hours < 18.5) { greeting = "Selamat Sore"; iconClass = "fa-sun"; iconColor = "text-orange-400"; }

    const greetText = document.getElementById('greeting-text');
    const greetIcon = document.getElementById('greeting-icon');
    const clock = document.getElementById('realtime-clock');

    if (greetText) greetText.innerText = greeting;
    if (greetIcon) greetIcon.className = `fa-solid ${iconClass} ${iconColor}`;
    if (clock) {
        const timeString = new Intl.DateTimeFormat('id-ID', { hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false, timeZone: 'Asia/Jakarta' }).format(now);
        clock.innerText = timeString + ' WIB';
    }
}

// Menjalankan fungsi setelah elemen halaman dirender oleh browser
document.addEventListener('DOMContentLoaded', () => {
    setInterval(updateAppHeader, 1000);
    updateAppHeader();
    renderCCTVGrid(); 
});
